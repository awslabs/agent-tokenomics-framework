/**
 * Tokenomics Advisor — control-plane page (chat-only).
 *
 * Live by default: each question is POSTed to /advisor/chats (stored with a
 * pending reply), answered asynchronously by the Advisor agent on AgentCore, and
 * the chat is polled until the reply is ready. Every figure in an answer comes
 * from the Advisor's read-only tools and is verified server-side; the evidence
 * block shows exactly those figures. Pattern popovers come from the Knowledge
 * Base (`citation_details`), so the raw catalog id is never shown.
 *
 * Chats are kept per admin for 90 days and can be reopened or deleted.
 *
 * Layout: header (the help panel
 * shows the page help) + a chat panel with a time-window selector + New chat, a message
 * thread where each answer carries an evidence mini-table and pattern chips,
 * starter chips (requirements §9), and an input box. No savings projection.
 */

