function EvidenceTable({ rows, caption }: { rows: AdvisorFinding[]; caption?: string }) {
  return (
    <Box margin={{ top: "s" }}>
      <Table
        variant="embedded"
        items={rows}
        columnDefinitions={[
          { id: "signal", header: "Signal", cell: (e) => e.signal, isRowHeader: true },
          { id: "observed", header: "Observed", cell: (e) => <b>{e.observed}</b> },
          { id: "level", header: "Level", cell: (e) => <Badge color="grey">{e.level}</Badge> },
        ]}
      />
      {caption && (
        <Box margin={{ top: "xs" }} variant="small" color="text-body-secondary">
          {caption}
        </Box>
      )}
    </Box>
  );
}

function riskColor(r: string) {
  return r === "high" ? "red" : r === "medium" || r === "low_medium" ? "blue" : "green";
}

const riskLabel = (r: string) => (r === "low_medium" ? "low–medium" : r);
const pillarLabel = (p: string) => (p ? p[0].toUpperCase() + p.slice(1) : p);

// A citation chip: blue badge showing the pattern NAME (+ muted #N). Clicking
// opens a popover with the pattern detail (never the raw catalog id).
function PatternChip({ p }: { p: AdvisorCitation }) {
  return (
    <Popover
      header={`${p.name}  ·  #${p.ref_no}`}
      position="top"
      size="medium"
      triggerType="custom"
      content={
        <SpaceBetween size="xs">
          <SpaceBetween direction="horizontal" size="xxs">
            <Badge color="blue">{pillarLabel(p.pillar)}</Badge>
            <Badge color={riskColor(p.quality_risk)}>{riskLabel(p.quality_risk)} risk</Badge>
          </SpaceBetween>
          <Box variant="p">{p.summary}</Box>
          <div>
            <Box variant="awsui-key-label">Expected effect</Box>
            <Box variant="p">{p.expected_effect}</Box>
          </div>
        </SpaceBetween>
      }
    >
      {/* A native button (not a bare span) so the chip is keyboard / screen-reader reachable. */}
      <button
        type="button"
        aria-label={`Pattern ${p.name}`}
        aria-haspopup="dialog"
        style={{ cursor: "pointer", background: "none", border: 0, padding: 0, font: "inherit" }}
      >
        <Badge color="blue">
          {p.name} · #{p.ref_no}
        </Badge>
      </button>
    </Popover>
  );
}

function Bubble({ m }: { m: AdvisorMessage }) {
  const isUser = m.role === "user";
  return (
    <div style={{ display: "flex", justifyContent: isUser ? "flex-end" : "flex-start" }}>
      <div
        style={{
          maxWidth: "80%",
          background: isUser ? "#e7f3ff" : "#f7f8fa",
          border: isUser ? "none" : "1px solid #e9ebed",
          borderRadius: 10,
          padding: "10px 14px",
        }}
      >
        {!isUser && (
          <Box margin={{ bottom: "xxs" }}>
            <Badge color="green">Advisor</Badge>
          </Box>
        )}
        <Box variant="p">
          <span style={{ whiteSpace: "pre-wrap" }}>{m.text}</span>
        </Box>
        {m.findings && m.findings.length > 0 && (
          <EvidenceTable rows={m.findings} caption={[EVIDENCE_CAPTION, ...(m.notes ?? [])].join(" ")} />
        )}
        {m.citation_details && m.citation_details.length > 0 && (
          <Box margin={{ top: "s" }}>
            <Box variant="small" color="text-body-secondary" margin={{ bottom: "xxs" }}>
              Referenced patterns
            </Box>
            <SpaceBetween direction="horizontal" size="xs">
              {m.citation_details.map((c) => (
                <PatternChip key={c.pattern_id} p={c} />
              ))}
            </SpaceBetween>
          </Box>
        )}
      </div>
    </div>
  );
}

function ago(iso?: string): string {
  if (!iso) return "";
  const s = Math.max(0, (Date.now() - new Date(iso).getTime()) / 1000);
  if (s < 60) return "just now";
  if (s < 3600) return `${Math.floor(s / 60)}m ago`;
  if (s < 86400) return `${Math.floor(s / 3600)}h ago`;
  return `${Math.floor(s / 86400)}d ago`;
}

// Collapsible chat-history panel to the right of the chat; it folds away to the right edge.
const NARROW_SCREEN_PX = 900;
// Below this row width (small window, or the help panel open) the chats fold away
// so the chat keeps a usable width; "Show chats" then opens them just for now.
const MIN_ROW_WIDTH_WITH_PANEL = 640;
const MIN_ROW_HEIGHT = 420;
const BOTTOM_GAP = 24;

// Height for the chat row: from its top edge to the bottom of the window, so both
// boxes always share one height and grow or shrink with the screen. Recomputed on
// window resize and when content above it (alerts, banners) moves it.
function useFillHeight(ref: { current: HTMLElement | null }): { height: number; width: number } {
  const [h, setH] = useState(MIN_ROW_HEIGHT);
  const [w, setW] = useState(window.innerWidth);
  useEffect(() => {
    const update = () => {
      const rect = ref.current?.getBoundingClientRect();
      setH(Math.max(MIN_ROW_HEIGHT, Math.floor(window.innerHeight - (rect?.top ?? 0) - BOTTOM_GAP)));
      if (rect) setW(rect.width);
    };
    update();
    window.addEventListener("resize", update);
    const ro = new ResizeObserver(update);
    if (ref.current?.parentElement) ro.observe(ref.current.parentElement);
    return () => {
      window.removeEventListener("resize", update);
      ro.disconnect();
    };
  }, [ref]);
  return { height: h, width: w };
}

function ChatPanel({
  chats,
  activeId,
  open,
  onToggle,
  onOpen,
  onDelete,
  onDeleteAll,
}: {
  chats: AdvisorChatSummary[];
  activeId: string | null;
  open: boolean;
  onToggle: () => void;
  onOpen: (id: string) => void;
  onDelete: (c: AdvisorChatSummary) => void;
  onDeleteAll: () => void;
}) {
  if (!open) {
    return (
      <div style={{ flexShrink: 0, paddingTop: 12 }}>
        <Button variant="icon" iconName="angle-left" ariaLabel="Show chats" onClick={onToggle} />
      </div>
    );
  }
  return (
    <div style={{ width: "clamp(200px, 18%, 280px)", flexShrink: 0, height: "100%" }}>
      <Container
        fitHeight
        header={
          <Header
            variant="h3"
            actions={
              <Button variant="icon" iconName="angle-right" ariaLabel="Hide chats" onClick={onToggle} />
            }
          >
            Chats
          </Header>
        }
        footer={
          <SpaceBetween size="xxs">
            {chats.length > 0 && (
              <Button variant="inline-link" iconName="remove" onClick={onDeleteAll}>
                Delete all chats
              </Button>
            )}
            <Box variant="small" color="text-body-secondary">
              Chats are kept for 90 days.
            </Box>
          </SpaceBetween>
        }
      >
        <SpaceBetween size="xs">
          {chats.length === 0 && (
            <Box variant="small" color="text-body-secondary">
              No chats yet.
            </Box>
          )}
          <div>
            {chats.map((c) => (
              <div
                key={c.chat_id}
                style={{
                  display: "flex",
                  alignItems: "center",
                  gap: 2,
                  borderRadius: 8,
                  padding: "2px 2px 2px 8px",
                  background: c.chat_id === activeId ? "#e7f3ff" : "transparent",
                }}
              >
                <button
                  type="button"
                  onClick={() => onOpen(c.chat_id)}
                  title={c.title}
                  style={{
                    flex: 1,
                    minWidth: 0,
                    textAlign: "left",
                    background: "none",
                    border: 0,
                    padding: "6px 0",
                    cursor: "pointer",
                  }}
                >
                  <div
                    style={{
                      fontWeight: c.chat_id === activeId ? 700 : 400,
                      overflow: "hidden",
                      textOverflow: "ellipsis",
                      whiteSpace: "nowrap",
                    }}
                  >
                    {c.title || "Untitled chat"}
                  </div>
                  <Box variant="small" color="text-body-secondary">
                    {c.pending ? "answering…" : ago(c.updated_at)}
                  </Box>
                </button>
                <Button
                  variant="icon"
                  iconName="remove"
                  ariaLabel={`Delete chat ${c.title}`}
                  onClick={() => onDelete(c)}
                />
              </div>
            ))}
          </div>
        </SpaceBetween>
      </Container>
    </div>
  );
}

export default function Advisor({ chatId: routeChatId = null }: { chatId?: string | null }) {
  const [windowSel, setWindowSel] = useState<SelectProps.Option>(WINDOW_OPTIONS[1] as SelectProps.Option);
  const [messages, setMessages] = useState<AdvisorMessage[]>([]);
  const [draft, setDraft] = useState("");
  const [thinking, setThinking] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [chatId, setChatIdState] = useState<string | null>(null);
  // Delete confirmation: a chat, "all", or nothing.
  const [confirmDelete, setConfirmDelete] = useState<AdvisorChatSummary | "all" | null>(null);
  const [history, setHistory] = useState<AdvisorChatSummary[]>([]);
  // Saved choice wins; otherwise the chat list starts open except on narrow screens.
  const [panelOpen, setPanelOpen] = useState(() => {
    const saved = localStorage.getItem("advisor.chatsOpen");
    return saved === null ? window.innerWidth >= NARROW_SCREEN_PX : saved !== "0";
  });
  // On a narrow row the saved choice is set aside: the panel opens only on demand.
  const [peek, setPeek] = useState(false);
  const rowRef = useRef<HTMLDivElement | null>(null);
  const { height: rowHeight, width: rowWidth } = useFillHeight(rowRef);
  const narrowRow = rowWidth < MIN_ROW_WIDTH_WITH_PANEL;
  // Bumped on New chat / opening another chat so stale replies are ignored.
  const generation = useRef(0);
  const currentChat = useRef<string | null>(null);
  const threadEnd = useRef<HTMLDivElement | null>(null);
  const setChatId = (id: string | null) => {
    currentChat.current = id;
    setChatIdState(id);
  };
  const refreshHistory = () => {
    api
      .listAdvisorChats()
      .then((r) => setHistory(r.chats))
      .catch((e) => setError((e as Error).message));
  };
  const togglePanel = () => {
    if (narrowRow) return setPeek(!peek);
    localStorage.setItem("advisor.chatsOpen", panelOpen ? "0" : "1");
    setPanelOpen(!panelOpen);
  };

  useEffect(() => {
    refreshHistory();
  }, []);

  // The URL drives which chat is open (#advisor/<id>).
  useEffect(() => {
    if (routeChatId && routeChatId !== currentChat.current) openChat(routeChatId);
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [routeChatId]);

  // Keep the newest message in view inside the scrolling chat panel.
  useEffect(() => {
    threadEnd.current?.scrollIntoView({ block: "nearest" });
  }, [messages, thinking]);

  // Leaving the page cancels any in-flight polling.
  useEffect(
    () => () => {
      generation.current += 1;
    },
    [],
  );

  const awaitReply = async (cid: string, messageId: string) => {
    const gen = generation.current;
    setThinking(true);
    try {
      const chat = await waitForAdvisorReply(cid, messageId, () => gen !== generation.current);
      if (chat && gen === generation.current) setMessages(shown(chat));
    } catch (e) {
      if (gen === generation.current) setError((e as Error).message);
    } finally {
      if (gen === generation.current) setThinking(false);
      refreshHistory();
    }
  };

  const send = async (text: string) => {
    const q = text.trim();
    if (!q || thinking) return;
    setError(null);
    setMessages((prev) => [...prev, { msg_id: "local", role: "user", text: q, status: "complete" }]);
    setDraft("");
    if (!chatId) generation.current += 1; // a new chat supersedes anything still loading
    const gen = generation.current;
    try {
      setThinking(true);
      const r = await api.sendAdvisorMessage({
        message: q,
        window: String(windowSel.value ?? "7d"),
        ...(chatId ? { chat_id: chatId } : {}),
      });
      if (gen !== generation.current) return;
      if (r.chat_id !== currentChat.current) {
        setChatId(r.chat_id);
        window.location.hash = `advisor/${r.chat_id}`; // deep link to this chat
      }
      refreshHistory();
      await awaitReply(r.chat_id, r.message_id);
    } catch (e) {
      if (gen === generation.current) {
        setError((e as Error).message);
        setThinking(false);
        // The question was not stored: take it back out of the thread.
        setMessages((prev) => prev.slice(0, -1));
        setDraft(q);
      }
    }
  };

  const newChat = () => {
    generation.current += 1;
    setMessages([]);
    setDraft("");
    setThinking(false);
    setError(null);
    setChatId(null);
  };

  const openChat = async (cid: string) => {
    newChat();
    const gen = generation.current;
    setThinking(true); // block sending until the chat has loaded
    try {
      const chat = await api.getAdvisorChat(cid);
      if (gen !== generation.current) return;
      setChatId(chat.chat_id);
      setMessages(shown(chat));
      const w = WINDOW_OPTIONS.find((o) => "value" in o && o.value === chat.window);
      if (w) setWindowSel(w as SelectProps.Option);
      const pending = chat.messages.find((m) => m.role === "assistant" && m.status === "pending");
      if (pending) await awaitReply(chat.chat_id, pending.msg_id);
      else setThinking(false);
    } catch (e) {
      if (gen === generation.current) {
        setError((e as Error).message);
        setThinking(false);
      }
    }
  };

  // New chat clears the thread and drops the chat id from the URL.
  const startNewChat = () => {
    newChat();
    window.location.hash = "advisor";
  };

  const confirmAndDelete = async () => {
    const target = confirmDelete;
    setConfirmDelete(null);
    if (!target) return;
    try {
      if (target === "all") {
        await api.deleteAllAdvisorChats();
        startNewChat();
      } else {
        await api.deleteAdvisorChat(target.chat_id);
        if (target.chat_id === chatId) startNewChat();
      }
    } catch (e) {
      setError((e as Error).message);
    } finally {
      refreshHistory();
    }
  };

  return (
    <SpaceBetween size="l">
      {error && (
        <Alert type="error" dismissible onDismiss={() => setError(null)} header="Advisor error">
          {error}
        </Alert>
      )}

      <div ref={rowRef} style={{ display: "flex", gap: 16, alignItems: "stretch", height: rowHeight }}>
        <div style={{ flex: 1, minWidth: 0, height: "100%" }}>
          <Container
            fitHeight
            footer={
              <div style={{ display: "flex", gap: 8 }}>
                <div style={{ flex: 1 }}>
                  <Input
                    value={draft}
                    onChange={(e) => setDraft(e.detail.value)}
                    onKeyDown={(e) => {
                      if (e.detail.key === "Enter") send(draft);
                    }}
                    placeholder="Ask about cost, agents, caching, users, limits…"
                    disabled={thinking}
                  />
                </div>
                <Button variant="primary" iconName="send" onClick={() => send(draft)} disabled={thinking}>
                  Send
                </Button>
              </div>
            }
            header={
              <Header
                variant="h2"
                description="The advisor is bound to the selected time window — it answers from your metrics in that period."
                actions={
                  <SpaceBetween direction="horizontal" size="xs">
                    <Select
                      selectedOption={windowSel}
                      onChange={(e) => setWindowSel(e.detail.selectedOption)}
                      options={WINDOW_OPTIONS}
                    />
                    <Button iconName="refresh" onClick={startNewChat}>
                      New chat
                    </Button>
                  </SpaceBetween>
                }
              >
                Ask the Tokenomics Advisor
              </Header>
            }
          >
            <SpaceBetween size="m">
              {/* starter chips */}
              <SpaceBetween size="xs">
                <Box variant="small" color="text-body-secondary">
                  SUGGESTED
                </Box>
                <SpaceBetween direction="horizontal" size="xs">
                  {STARTERS.map((s) => (
                    <Button key={s.label} onClick={() => send(s.q)} disabled={thinking}>
                      {s.label}
                    </Button>
                  ))}
                </SpaceBetween>
              </SpaceBetween>

              {/* thread */}
              {messages.length === 0 ? (
                <Box textAlign="center" color="text-body-secondary" padding="l">
                  <b>Ask about your live agents' token economics.</b>
                  <Box variant="p" color="text-body-secondary">
                    Pick a suggested question above, or ask about a specific agent, user, or the cache.
                  </Box>
                </Box>
              ) : (
                <SpaceBetween size="m">
                  {messages.map((m, i) => (
                    <Bubble key={i} m={m} />
                  ))}
                  {thinking && (
                    <Box color="text-body-secondary">
                      <Spinner /> &nbsp;Advisor is analysing your metrics…
                    </Box>
                  )}
                </SpaceBetween>
              )}
              <div ref={threadEnd} />
            </SpaceBetween>
          </Container>
        </div>
        <ChatPanel
          chats={history}
          activeId={chatId}
          open={narrowRow ? peek : panelOpen}
          onToggle={togglePanel}
          onOpen={(id) => (window.location.hash = `advisor/${id}`)}
          onDelete={(c) => setConfirmDelete(c)}
          onDeleteAll={() => setConfirmDelete("all")}
        />
      </div>

      <Modal
        visible={confirmDelete !== null}
        onDismiss={() => setConfirmDelete(null)}
        header={confirmDelete === "all" ? "Delete all chats?" : "Delete chat?"}
        footer={
          <Box float="right">
            <SpaceBetween direction="horizontal" size="xs">
              <Button variant="link" onClick={() => setConfirmDelete(null)}>
                Cancel
              </Button>
              <Button variant="primary" onClick={confirmAndDelete}>
                Delete
              </Button>
            </SpaceBetween>
          </Box>
        }
      >
        {confirmDelete === "all"
          ? "This permanently deletes all of your Advisor chats. Other admins' chats are not affected."
          : `This permanently deletes "${confirmDelete?.title ?? ""}".`}
      </Modal>
    </SpaceBetween>
  );
}
